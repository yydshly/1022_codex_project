"""Generate a native macOS SwiftUI gallery calling all 41 public modifiers."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate() -> str:
    manifest = json.loads((ROOT / "web/shaders.json").read_text(encoding="utf-8"))
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    specs, cases = [], []
    for shader in manifest["shaders"]:
        params, args = [], []
        for p in shader["params"]:
            key = p["label"]
            if p["type"] == "point":
                args.append(f"{key}: touch")
                continue
            lo = min(p["min"] if p["min"] is not None else p["uiMin"], p["default"])
            hi = max(p["max"] if p["max"] is not None else p["uiMax"], p["default"])
            params.append(f"Parameter(key: {quote(key)}, name: {quote(p['name'])}, initial: {p['default']}, lower: {lo}, upper: {hi})")
            args.append(f"{key}: Float(age)" if key == "touchAge" else f"{key}: Float(value({quote(key)}))")
        specs.append(f"        Effect(id: {quote(shader['id'])}, name: {quote(shader['name'])}, title: {quote(shader['title'])}, summary: {quote(shader['description'])}, parameters: [{', '.join(params)}])")
        cases.append(f"        case {quote(shader['id'])}: return AnyView(content.{shader['modifier']}({', '.join(args)}))")
    return '''// Generated by scripts/build_native.py. Do not edit the 41-case mapping by hand.
// Calls the unmodified upstream SwiftUIShaders package; see ../upstream/LICENSE.
import SwiftUI

struct Parameter: Identifiable {
    let key: String
    let name: String
    let initial: Double
    let lower: Double
    let upper: Double
    var id: String { key }
}

struct Effect: Identifiable {
    let id: String
    let name: String
    let title: String
    let summary: String
    let parameters: [Parameter]
    static let all: [Effect] = [
''' + ",\n".join(specs) + '''
    ]
}

@main
struct ShaderGalleryApp: App {
    var body: some Scene {
        WindowGroup("SwiftUI Shader Lab · Native Metal") {
            GalleryView().frame(minWidth: 1020, minHeight: 760).preferredColorScheme(.dark)
        }
    }
}

struct GalleryView: View {
    @State private var selection = "Holographic"
    @State private var values: [String: Double] = [:]
    @State private var touch = UnitPoint.center
    @State private var touchDate: Date?
    @State private var compare = false
    private var effect: Effect { Effect.all.first { $0.id == selection } ?? Effect.all[0] }

    private func value(_ key: String) -> Double {
        values[key] ?? effect.parameters.first { $0.key == key }?.initial ?? 0
    }

    private func reset() {
        values = [:]
        touch = .center
        touchDate = nil
    }

    private var cover: some View {
        Image("sample-cover").resizable().scaledToFit().frame(width: 360, height: 480)
    }

    var body: some View {
        HStack(spacing: 0) {
            List(selection: $selection) {
                ForEach(Effect.all) { item in
                    VStack(alignment: .leading, spacing: 4) {
                        Text(item.name).font(.headline)
                        Text(item.title).font(.caption).foregroundStyle(.secondary)
                    }.padding(.vertical, 6).tag(item.id)
                }
            }.frame(width: 220)
            VStack(spacing: 22) {
                Text(effect.name).font(.largeTitle)
                Text(effect.title).foregroundStyle(.secondary)
                Group {
                    if compare { cover }
                    else if selection == "TouchRipple" {
                        TimelineView(.animation) { context in
                            applied(cover, age: touchDate.map { context.date.timeIntervalSince($0) } ?? value("touchAge"))
                        }
                    } else { applied(cover, age: value("touchAge")) }
                }
                .contentShape(Rectangle())
                .gesture(DragGesture(minimumDistance: 0).onChanged { drag in
                    touch = UnitPoint(x: min(1, max(0, drag.location.x / 360)),
                                      y: min(1, max(0, drag.location.y / 480)))
                    touchDate = Date()
                })
                .shadow(radius: 20)
                Toggle("显示原图", isOn: $compare).toggleStyle(.switch).frame(width: 150)
                Text("原始 Metal · 41 个公开修饰器 · 点击或拖动触摸交互效果")
                    .font(.caption).foregroundStyle(.secondary)
            }.frame(maxWidth: .infinity).padding(24)
            Divider()
            ScrollView {
                VStack(alignment: .leading, spacing: 20) {
                    HStack { Text("全部参数").font(.headline); Spacer(); Button("恢复默认", action: reset) }
                    Text(effect.summary).font(.callout).foregroundStyle(.secondary)
                    ForEach(effect.parameters) { parameter in
                        VStack(alignment: .leading, spacing: 7) {
                            HStack {
                                Text(parameter.name)
                                Spacer()
                                Text(value(parameter.key), format: .number.precision(.fractionLength(0...3))).monospacedDigit()
                            }.font(.callout)
                            Slider(value: Binding(get: { value(parameter.key) }, set: { values[parameter.key] = $0; if parameter.key == "touchAge" { touchDate = nil } }),
                                   in: parameter.lower...parameter.upper)
                            Text(parameter.key).font(.caption.monospaced()).foregroundStyle(.secondary)
                        }
                    }
                    if selection == "RefractLens" || selection == "TouchRipple" {
                        Text("拖动封面更新 touchPos；涟漪的 touchAge 由 TimelineView 持续推进，也可手动调节。")
                            .font(.caption).foregroundStyle(.secondary)
                    }
                    Text("与网页的 WebGL 移植预览对照时，请使用相同参数。原生默认 maxSampleOffset 为 64×64，强位移可能受到采样边界限制。")
                        .font(.caption).foregroundStyle(.secondary)
                    Link("查看上游源码 ↗", destination: URL(string: "https://github.com/krispuckett/SwiftUIShaders/tree/6b644a8bd4f3131401bd6765990e476352d3cdef")!)
                }.padding(22)
            }.frame(width: 300)
        }
        .onChange(of: selection) { _, _ in reset() }
    }

    private func applied<V: View>(_ content: V, age: Double) -> AnyView {
        switch selection {
''' + "\n".join(cases) + '''
        default: return AnyView(content)
        }
    }
}
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "native/ShaderGalleryApp.swift"
    text = generate().replace("import SwiftUI\n", "import SwiftUI\nimport SwiftUIShaders\n", 1)
    if args.check:
        assert target.read_text(encoding="utf-8") == text, "Native gallery needs regeneration"
    else:
        target.parent.mkdir(exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
    print("Native SwiftUI gallery: 41/41 public modifiers mapped.")
