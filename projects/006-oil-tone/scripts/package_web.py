"""Build the oil-tone study's static data and rerun the pinned upstream linter."""
from __future__ import annotations

import argparse
import contextlib
import hashlib
import io
import json
from pathlib import Path
import platform
import re
import runpy
import shutil

ROOT = Path(__file__).resolve().parents[1]


def build(check: bool = False) -> None:
    data = json.loads((ROOT / "content.json").read_text(encoding="utf-8"))
    source = (ROOT / "upstream/SKILL.md").read_text(encoding="utf-8")
    lines = source.splitlines()
    assert len(data["rules"]) == 23
    for rule in data["rules"]:
        rule["source"] = lines[rule["line"] - 1]
    assert len({rule["id"] for rule in data["rules"]}) == 23
    data["writingPrompt"] = (ROOT / "prompts/oil-tone-writing-prompt.txt").read_text(encoding="utf-8")
    prompt_rules = re.findall(r"^\[([A-E][1-7])\]", data["writingPrompt"], re.MULTILINE)
    assert len(prompt_rules) == 23 and set(prompt_rules) == {rule["id"] for rule in data["rules"]}
    for revision in data["revisions"]:
        assert data["original"].count(revision["quote"]) == 1, revision["title"]
        assert set(revision["rules"]) <= {rule["id"] for rule in data["rules"]}
    positions = sorted((data["original"].index(r["quote"]), len(r["quote"])) for r in data["revisions"])
    assert all(a + length <= b for (a, length), (b, _) in zip(positions, positions[1:]))
    lint = runpy.run_path(str(ROOT / "upstream/tone_lint.py"))
    capture = io.StringIO()
    with contextlib.redirect_stdout(capture):
        status = lint["self_test"]()
    assert status == 0
    results = {
        "commit": data["meta"]["sha"],
        "study_date": data["meta"]["date"],
        "python": platform.python_version(),
        "method": "Pinned upstream find_warnings on the exact original and final strings in content.json; no model API or performance experiment.",
        "self_test": capture.getvalue().strip(),
        "rule_count": len(lint["WARNING_RULES"]),
    }
    for key in ("original", "final"):
        matches = lint["find_warnings"](data[key])
        results[key] = {
            "characters": len(data[key]),
            "warnings": [{"line": n, "text": text, "advice": advice} for n, text, advice in matches],
            "warning_count": len(matches),
            "warned_lines": len({row[0] for row in matches}),
        }
    assert results["original"]["warning_count"] == 9
    assert results["final"]["warning_count"] == 0
    assert (100 - 35) / 100 == 0.65
    data["lint"] = results
    data["sources"] = {name: (ROOT / "upstream" / name).read_text(encoding="utf-8")
                       for name in ("SKILL.md", "tone_lint.py", "openai.yaml", "LICENSE")}
    report = json.dumps(results, ensure_ascii=False, indent=2) + "\n"
    bundle = "// Generated by scripts/package_web.py; edit content.json or upstream snapshots.\nwindow.OIL_TONE_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    outputs = {
        ROOT / "web/data.js": bundle,
        ROOT / "examples/original.md": data["original"] + "\n",
        ROOT / "examples/final.md": data["final"] + "\n",
        ROOT / "examples/lint-results.json": report,
    }
    # Python's version is execution metadata. Retain the recorded version for unchanged check output.
    if check:
        previous = json.loads((ROOT / "examples/lint-results.json").read_text(encoding="utf-8"))
        results["python"] = previous["python"]
        data["lint"]["python"] = previous["python"]
        outputs[ROOT / "examples/lint-results.json"] = json.dumps(results, ensure_ascii=False, indent=2) + "\n"
        outputs[ROOT / "web/data.js"] = "// Generated by scripts/package_web.py; edit content.json or upstream snapshots.\nwindow.OIL_TONE_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    for path, text in outputs.items():
        if check:
            assert path.read_text(encoding="utf-8") == text, f"Stale generated file: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    copies = [(ROOT / "assets/cover.svg", ROOT / "web/assets/cover.svg")]
    copies += [(ROOT / "assets/understanding-summary.png", ROOT / "web/assets/understanding-summary.png")]
    copies += [(ROOT / "upstream" / name, ROOT / "web/assets/source" / name)
               for name in ("SKILL.md", "tone_lint.py", "openai.yaml", "LICENSE", "manifest.json")]
    copies += [(ROOT / "examples/lint-results.json", ROOT / "web/assets/lint-results.json")]
    copies += [(ROOT / "prompts/oil-tone-writing-prompt.txt", ROOT / "web/assets/oil-tone-writing-prompt.txt")]
    for source_path, destination in copies:
        if check:
            assert source_path.read_bytes() == destination.read_bytes(), f"Stale asset: {destination}"
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source_path, destination)
    manifest = json.loads((ROOT / "upstream/manifest.json").read_text(encoding="utf-8"))
    for item in manifest["files"]:
        assert hashlib.sha256((ROOT / "upstream" / item["local"]).read_bytes()).hexdigest() == item["sha256"]
    print(f"{'Checked' if check else 'Packaged'}: 23 rules, {len(data['revisions'])} revisions; linter 9 → 0 warnings.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    build(args.check)
