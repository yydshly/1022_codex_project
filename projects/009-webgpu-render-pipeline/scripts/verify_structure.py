"""Check research completeness, local references, image integrity and generated outputs."""
from __future__ import annotations

from html.parser import HTMLParser
import json
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit
import xml.etree.ElementTree as ET

from build_research import generate
from package_web import main as package

PROJECT = Path(__file__).resolve().parents[1]


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []
        self.ids = set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if "id" in attrs:
            assert attrs["id"] not in self.ids, f"Duplicate DOM id: {attrs['id']}"
            self.ids.add(attrs["id"])
        for name in ("href", "src"):
            if name in attrs:
                self.links.append(attrs[name])
        if tag == "img":
            assert "alt" in attrs, "Image missing alt"


def main():
    summary = generate(True)
    packaged = package(True)
    parser = Links()
    parser.feed((PROJECT / "web/index.html").read_text(encoding="utf-8"))
    # Category headings are generated by app.js from the canonical research data.
    parser.ids.update('group-' + item['category'] for item in json.loads((PROJECT / 'capabilities.json').read_text(encoding='utf-8')))
    checked = 0
    for link in parser.links:
        parsed = urlsplit(link)
        if parsed.scheme or parsed.netloc:
            continue
        if parsed.path:
            target = (PROJECT / "web" / unquote(parsed.path)).resolve()
            assert target.is_relative_to((PROJECT / "web").resolve()) and target.is_file(), f"Missing page resource: {link}"
            checked += 1
        elif parsed.fragment:
            assert parsed.fragment in parser.ids, f"Missing section anchor: {link}"
    for document in PROJECT.glob("*.md"):
        for link in re.findall(r"\]\(([^)]+)\)", document.read_text(encoding="utf-8")):
            parsed = urlsplit(link)
            if not parsed.scheme and parsed.path:
                assert (document.parent / unquote(parsed.path)).exists(), f"Missing Markdown link: {document.name}: {link}"
    diagrams = list((PROJECT / "assets").glob("*.svg"))
    for diagram in diagrams:
        ET.parse(diagram)
    assert len(json.loads((PROJECT / "capabilities.json").read_text(encoding="utf-8"))) == 89
    assert not any("__NAME__" in file.read_text(encoding="utf-8") for file in PROJECT.glob("*.md"))
    print(json.dumps({**summary, "algorithm_groups": packaged["algorithm_groups"], "light_steps": packaged["light_steps"], "comparison_rows": packaged["comparison_rows"], "everyday_scenarios": packaged["everyday_scenarios"], "packaged_files": packaged["packaged_files"], "runtime_files": packaged["runtime_files"], "html_local_resources": checked, "markdown_links": "pass", "svg_diagrams": len(diagrams), "media_hashes": "pass"}, ensure_ascii=False))


if __name__ == "__main__":
    main()
