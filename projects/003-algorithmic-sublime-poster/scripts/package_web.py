def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that published media matches the originals")
    args = parser.parse_args()
    for filename in FILES:
        source = PROJECT / "assets" / filename
        destination = PROJECT / "web" / "assets" / filename
        if not source.is_file():
            parser.error(f"Missing attributed source asset: {source}")
        if args.check:
            if not destination.is_file() or destination.read_bytes() != source.read_bytes():
                parser.error(f"Stale or missing web asset: {destination}; run package_web.py")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, destination)
    print(f"{'Verified' if args.check else 'Packaged'} {len(FILES)} unchanged web assets.")


if __name__ == "__main__":
    main()
